def make_opt(text, score):
    return {"text": text, "main": "", "score": score}

def build_q(dim, layer, sceneTag, stem, texts, reverse=False):
    """texts: [+1.0, +0.3, -0.3, -1.0] 对应四个选项文案"""
    return {
        "dim": dim,
        "layer": layer,
        "sceneTag": sceneTag,
        "stem": stem,
        "mains": ["", "", "", ""],
        "opts": [
            make_opt(texts[0], 1.0),
            make_opt(texts[1], 0.3),
            make_opt(texts[2], -0.3),
            make_opt(texts[3], -1.0),
        ],
        "reverseCheck": reverse,
    }


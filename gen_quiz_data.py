def assign_ids(all_qs):
    out = []
    counters = {}
    for q in all_qs:
        dim = q['dim']
        counters[dim] = counters.get(dim, 0) + 1
        q['id'] = f"{dim.lower()}{counters[dim]:03d}"
        out.append(q)
    return out

def main():
    existing = load_existing()
    all_qs = D1 + D2 + D3 + D4 + D5 + D6
    questions = assign_ids(all_qs)

    # 保留现有 personalities, dimLabels, profiles
    output = {
        "version": "v8",
        "dims": existing.get("dims", ["D1","D2","D3","D4","D5","D6"]),
        "dimLabels": existing.get("dimLabels", {}),
        "personalities": existing.get("personalities", {}),
        "profiles": existing.get("profiles", {}),
        "questions": questions,
    }

    with open(DST, 'w', encoding='utf-8') as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    print(f"Generated {len(questions)} questions")
    import collections
    c = collections.Counter(q['dim'] for q in questions)
    for d in output['dims']:
        rev = sum(1 for q in questions if q['dim']==d and q.get('reverseCheck'))
        print(f"  {d}: {c[d]} (reverse={rev})")

